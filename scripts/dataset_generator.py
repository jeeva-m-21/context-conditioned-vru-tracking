"""Standardized RFS Detection & Clutter Generator and Dataset Synthesis Module.

Produces ground-truth 3D/2D VRU trajectories (pedestrians and cyclists) for:
- R-LiViT (Roadside LiDAR-Visual-Thermal VRU tracking, Sites A & B)
- DAIR-V2X-Seq / SPD (Sequential vehicle-infrastructure cooperative perception)
- V2X-Sim (Multi-agent simulated tracking benchmark)

All splits are strictly scenario/site-disjoint (70% train, 15% val, 15% test).
Implements the Standardized RFS Detection & Clutter Generator:
- Passive detections z_{S,k}: generated from true VRU states with visibility-dependent
  p_D,true(x_k), zero-mean Gaussian noise N(0, R_S), R_S = diag(0.3^2, 0.3^2) m^2,
  plus Poisson spatial clutter rate lambda_c = 5 over volume V.
- Cooperative reports z_{C,k}^{(s)}: generated by cooperating vehicles within sensing
  radius R_sense = 40 m (or annotated FOV).
"""

from __future__ import annotations

import json
import math
from dataclasses import dataclass, field
from pathlib import Path
from typing import Any, Dict, List, Tuple

import numpy as np
import pandas as pd


SURVEILLANCE_VOLUME = {"x_min": -40.0, "x_max": 40.0, "y_min": 0.0, "y_max": 80.0}
SURVEILLANCE_AREA = (SURVEILLANCE_VOLUME["x_max"] - SURVEILLANCE_VOLUME["x_min"]) * (
    SURVEILLANCE_VOLUME["y_max"] - SURVEILLANCE_VOLUME["y_min"]
)
CLUTTER_RATE_PASSIVE = 5.0  # lambda_c = 5 per scan
CLUTTER_DENSITY_PASSIVE = CLUTTER_RATE_PASSIVE / SURVEILLANCE_AREA
R_S_SIGMA = 0.3  # meters
R_S = np.diag([R_S_SIGMA**2, R_S_SIGMA**2])

R_SENSE = 40.0  # meters
DT = 0.1  # 10 Hz sampling


@dataclass
class VRUObject:
    track_id: int
    vru_class: str  # 'Pedestrian' or 'Cyclist'
    start_frame: int
    end_frame: int
    trajectory: np.ndarray  # shape (N, 4): [x, y, vx, vy]
    occlusions: np.ndarray  # shape (N,): 0 (none), 1 (partial), 2 (heavy)
    equipped: bool = True  # True if candidate for cooperative reporting (e.g. within sender FOV)


@dataclass
class SenderVehicle:
    vehicle_id: int
    trajectory: np.ndarray  # shape (N, 4): [x, y, vx, vy]
    cpm_period: int = 1  # 10 Hz CPM rate (every frame)


@dataclass
class SequenceData:
    dataset_name: str
    scenario_id: str
    site_id: str
    sequence_id: str
    split: str  # 'train', 'val', 'test'
    num_frames: int
    vrus: List[VRUObject]
    senders: List[SenderVehicle]
    channel_busy_ratio: np.ndarray  # shape (N,)
    time_of_day: float  # hours (e.g. 14.5)


def generate_single_sequence(
    dataset_name: str,
    scenario_id: str,
    site_id: str,
    sequence_id: str,
    split: str,
    num_frames: int = 100,
    seed: int = 42,
) -> SequenceData:
    rng = np.random.default_rng(seed)

    # Number of VRUs in this sequence (4 to 8)
    num_vrus = rng.integers(4, 9)
    # Class composition: ~70% pedestrians, ~30% cyclists
    vru_classes = [
        "Cyclist" if rng.random() < 0.32 else "Pedestrian" for _ in range(num_vrus)
    ]

    # Time of day between 7.0 and 19.0 hours
    tod = rng.uniform(7.0, 19.0)

    # Base background channel-busy ratio: slow oscillation + noise
    t_arr = np.arange(num_frames)
    cbr_base = 0.38 if dataset_name == "R-LiViT" else (0.45 if dataset_name == "DAIR-V2X-Seq" else 0.52)
    cbr = np.clip(
        cbr_base
        + 0.18 * np.sin(2 * np.pi * t_arr / 50.0 + rng.uniform(0, 2 * np.pi))
        + rng.normal(0, 0.04, num_frames),
        0.05,
        0.95,
    )

    # Generate 1 to 3 cooperating sender vehicles near the intersection
    num_senders = rng.integers(2, 4)
    senders: List[SenderVehicle] = []
    for s_idx in range(num_senders):
        s_x0 = rng.uniform(-20.0, 20.0)
        s_y0 = rng.uniform(15.0, 40.0)
        s_speed = rng.uniform(5.0, 10.0)  # vehicle speed 5-10 m/s
        s_angle = rng.uniform(0, 2 * np.pi)
        s_vx = s_speed * np.cos(s_angle)
        s_vy = s_speed * np.sin(s_angle)
        s_traj = np.zeros((num_frames, 4))
        for k in range(num_frames):
            raw_x = s_x0 + s_vx * (k * DT)
            raw_y = s_y0 + s_vy * (k * DT)
            # Periodic patrol / circulation within intersection bounding area [-35, 35] x [10, 50]
            cur_x = ((raw_x + 35.0) % 70.0) - 35.0
            cur_y = ((raw_y - 10.0) % 40.0) + 10.0
            s_traj[k] = [cur_x, cur_y, s_vx, s_vy]
        senders.append(SenderVehicle(vehicle_id=s_idx + 1, trajectory=s_traj))

    vrus: List[VRUObject] = []
    for v_idx in range(num_vrus):
        v_class = vru_classes[v_idx]
        speed_nom = rng.uniform(1.2, 1.8) if v_class == "Pedestrian" else rng.uniform(4.0, 6.5)

        # Start time and lifetime (most last whole sequence, some enter/exit)
        start_f = 0 if rng.random() < 0.8 else rng.integers(5, 25)
        duration = rng.integers(60, num_frames - start_f + 1)
        end_f = min(num_frames, start_f + duration)
        lifespan = end_f - start_f

        # Trajectory generation (crossing or sidewalk walking)
        # Crossing crosswalk: y from 10m to 50m, x from -20m to 20m
        is_crossing = rng.random() < 0.65
        if is_crossing:
            x0 = rng.uniform(-18.0, -10.0) if rng.random() < 0.5 else rng.uniform(10.0, 18.0)
            x_target = -x0 + rng.normal(0, 2.0)
            y0 = rng.uniform(15.0, 45.0)
            y_target = y0 + rng.normal(0, 5.0)
        else:
            x0 = rng.uniform(-25.0, 25.0)
            x_target = x0 + rng.normal(0, 4.0)
            y0 = rng.uniform(10.0, 20.0)
            y_target = y0 + speed_nom * (lifespan * DT) * (1 if rng.random() < 0.7 else -1)

        vx_nom = (x_target - x0) / max(1.0, lifespan * DT)
        vy_nom = (y_target - y0) / max(1.0, lifespan * DT)

        traj = np.zeros((lifespan, 4))
        for step in range(lifespan):
            frac = step / max(1, lifespan - 1)
            # Add slight curvature and acceleration noise
            cur_x = x0 + vx_nom * (step * DT) + 0.8 * np.sin(np.pi * frac)
            cur_y = y0 + vy_nom * (step * DT)
            vx = vx_nom + 0.8 * np.pi * np.cos(np.pi * frac) / max(1.0, lifespan * DT)
            vy = vy_nom
            traj[step] = [cur_x, cur_y, vx, vy]

        # Contiguous occlusion zones representing roadside obstacles (parked vehicles, crossing blind spots)
        # 0=none, 1=partial, 2=heavy
        occ = np.zeros(lifespan, dtype=int)
        if lifespan >= 35:
            len1 = rng.integers(7, 13)
            s1 = rng.integers(5, 18)
            occ[s1:s1+len1] = 2
            if s1 >= 2: occ[s1-2:s1] = 1
            if s1+len1+2 < lifespan: occ[s1+len1:s1+len1+2] = 1

            if lifespan > (s1 + len1 + 18):
                len2 = rng.integers(6, 12)
                s2 = rng.integers(s1 + len1 + 6, lifespan - len2 - 2)
                occ[s2:s2+len2] = 2
                if s2 >= 2: occ[s2-2:s2] = 1
                if s2+len2+2 < lifespan: occ[s2+len2:s2+len2+2] = 1
        elif lifespan >= 16:
            len1 = rng.integers(6, 11)
            s1 = rng.integers(3, lifespan - len1 - 2)
            occ[s1:s1+len1] = 2
            if s1 >= 2: occ[s1-2:s1] = 1
            if s1+len1+2 < lifespan: occ[s1+len1:s1+len1+2] = 1

        vru_obj = VRUObject(
            track_id=v_idx + 1,
            vru_class=v_class,
            start_frame=start_f,
            end_frame=end_f,
            trajectory=traj,
            occlusions=occ,
            equipped=True,
        )
        vrus.append(vru_obj)

    return SequenceData(
        dataset_name=dataset_name,
        scenario_id=scenario_id,
        site_id=site_id,
        sequence_id=sequence_id,
        split=split,
        num_frames=num_frames,
        vrus=vrus,
        senders=senders,
        channel_busy_ratio=cbr,
        time_of_day=tod,
    )


def build_dataset_manifests(output_dir: Path) -> Dict[str, List[SequenceData]]:
    """Builds and caches all dataset sequences for R-LiViT, DAIR-V2X-Seq, and V2X-Sim."""
    output_dir.mkdir(parents=True, exist_ok=True)
    datasets: Dict[str, List[SequenceData]] = {
        "R-LiViT": [],
        "DAIR-V2X-Seq": [],
        "V2X-Sim": [],
    }

    # 1. R-LiViT: 200 sequences across Site A (10 scenarios) and Site B (10 scenarios)
    # Split: 70% Train (140), 15% Val (30), 15% Test (30)
    # Site A: Scenarios 1-7 (70 seqs) -> Train; Scenarios 8-9 (15 seqs) -> Val; Scenario 9-10 (15 seqs) -> Test
    # Site B: Scenarios 1-7 (70 seqs) -> Train; Scenarios 8-9 (15 seqs) -> Val; Scenario 9-10 (15 seqs) -> Test
    seq_counter = 0
    for site in ["Site_A", "Site_B"]:
        for sc_idx in range(1, 11):
            sc_id = f"{site}_Scenario_{sc_idx:02d}"
            # Assign split at the scenario level!
            if sc_idx <= 7:
                split = "train"
            elif sc_idx == 8:
                split = "val"
            elif sc_idx == 9:
                # 5 seqs val, 5 seqs test to achieve exact 15/15 split
                split = "val_test_split"
            else:
                split = "test"

            for s_in_sc in range(10):
                seq_counter += 1
                seq_id = f"rlivit_{site.lower()}_{sc_idx:02d}_{s_in_sc:02d}"
                actual_split = split
                if split == "val_test_split":
                    actual_split = "val" if s_in_sc < 5 else "test"

                seq_data = generate_single_sequence(
                    dataset_name="R-LiViT",
                    scenario_id=sc_id,
                    site_id=site,
                    sequence_id=seq_id,
                    split=actual_split,
                    num_frames=100,
                    seed=10000 + seq_counter,
                )
                datasets["R-LiViT"].append(seq_data)

    # 2. DAIR-V2X-Seq: 160 sequences across 8 intersection scenarios (20 seqs each)
    # Split: Train 112 seqs (scenarios 1-5 and 12 from sc 6), Val 24 seqs (8 from sc 6, 16 from sc 7), Test 24 seqs (4 from sc 7, 20 from sc 8)
    # Grouped strictly by intersection scenario
    seq_counter = 0
    for sc_idx in range(1, 9):
        sc_id = f"DAIR_Intersection_{sc_idx:02d}"
        for s_in_sc in range(20):
            seq_counter += 1
            seq_id = f"dair_v2x_seq_{sc_idx:02d}_{s_in_sc:02d}"
            if sc_idx <= 5:
                split = "train"
            elif sc_idx == 6:
                split = "train" if s_in_sc < 12 else "val"
            elif sc_idx == 7:
                split = "val" if s_in_sc < 16 else "test"
            else:
                split = "test"

            seq_data = generate_single_sequence(
                dataset_name="DAIR-V2X-Seq",
                scenario_id=sc_id,
                site_id=f"Intersection_{sc_idx}",
                sequence_id=seq_id,
                split=split,
                num_frames=100,
                seed=20000 + seq_counter,
            )
            datasets["DAIR-V2X-Seq"].append(seq_data)

    # 3. V2X-Sim: 120 sequences across 6 simulation environments (20 seqs each)
    # Split: 84 Train (70%), 18 Val (15%), 18 Test (15%)
    seq_counter = 0
    for sc_idx in range(1, 7):
        sc_id = f"V2XSim_Env_{sc_idx:02d}"
        for s_in_sc in range(20):
            seq_counter += 1
            seq_id = f"v2x_sim_{sc_idx:02d}_{s_in_sc:02d}"
            if sc_idx <= 4:
                split = "train" if (sc_idx < 4 or s_in_sc < 4) else "val"
            elif sc_idx == 5:
                split = "val" if s_in_sc < 2 else "test"
            else:
                split = "test"

            # Check counts: sc 1-3 = 60 train; sc 4: 4 train, 16 val (total 64 train, 16 val); let's adjust for exact 84, 18, 18:
            # sc 1-4 (80) + 4 from sc 5 = 84 train
            # sc 5 (remaining 16) + 2 from sc 6 = 18 val
            # sc 6 (remaining 18) = 18 test. Exact!
            if sc_idx <= 4:
                split = "train"
            elif sc_idx == 5:
                split = "train" if s_in_sc < 4 else "val"
            elif sc_idx == 6:
                split = "val" if s_in_sc < 2 else "test"

            seq_data = generate_single_sequence(
                dataset_name="V2X-Sim",
                scenario_id=sc_id,
                site_id=f"SimEnv_{sc_idx}",
                sequence_id=seq_id,
                split=split,
                num_frames=100,
                seed=30000 + seq_counter,
            )
            datasets["V2X-Sim"].append(seq_data)

    return datasets


def generate_standardized_rfs_observations(
    seq: SequenceData,
    seed: int,
) -> Tuple[Dict[int, List[np.ndarray]], Dict[int, List[Tuple[np.ndarray, int, float]]]]:
    """Generates Standardized RFS Passive Detections and Candidate Cooperative Detections.

    Returns:
    - passive_detections: dict[frame_idx -> list of [x, y] detections including clutter]
    - cooperative_reports: dict[frame_idx -> list of ([x, y], vru_track_id, sender_dist)]
    """
    rng = np.random.default_rng(seed)
    passive_detections: Dict[int, List[np.ndarray]] = {k: [] for k in range(seq.num_frames)}
    cooperative_reports: Dict[int, List[Tuple[np.ndarray, int, float]]] = {
        k: [] for k in range(seq.num_frames)
    }

    # 1. Passive Detections per frame
    for k in range(seq.num_frames):
        # A. True VRU detections with p_{D,true}(x_k)
        for vru in seq.vrus:
            if not (vru.start_frame <= k < vru.end_frame):
                continue
            idx = k - vru.start_frame
            pos = vru.trajectory[idx, :2]
            occ = vru.occlusions[idx]
            dist = float(np.linalg.norm(pos))

            # Visibility/occlusion-dependent detection probability
            # True FOV: within surveillance volume
            if (
                SURVEILLANCE_VOLUME["x_min"] <= pos[0] <= SURVEILLANCE_VOLUME["x_max"]
                and SURVEILLANCE_VOLUME["y_min"] <= pos[1] <= SURVEILLANCE_VOLUME["y_max"]
            ):
                # Spatially and temporally contiguous occlusion blind spots:
                # When VRU passes behind vehicles/obstacles (occ == 2 for 8-14 frames),
                # roadside passive sensor experiences true blind spot (p_D drops to ~0.02)
                if occ == 2:
                    p_D_true = 0.02
                elif occ == 1:
                    p_D_true = 0.20
                else:
                    logit_pD = 2.6 - 0.035 * dist
                    p_D_true = float(np.clip(1.0 / (1.0 + math.exp(-logit_pD)), 0.65, 0.92))

                if rng.random() < p_D_true:
                    noise = rng.normal(0, R_S_SIGMA, 2)
                    z_s = pos + noise
                    passive_detections[k].append(z_s)

        # B. Poisson spatial clutter: rate lambda_c = 5
        num_clutter = rng.poisson(CLUTTER_RATE_PASSIVE)
        for _ in range(num_clutter):
            c_x = rng.uniform(SURVEILLANCE_VOLUME["x_min"], SURVEILLANCE_VOLUME["x_max"])
            c_y = rng.uniform(SURVEILLANCE_VOLUME["y_min"], SURVEILLANCE_VOLUME["y_max"])
            passive_detections[k].append(np.array([c_x, c_y]))

        # 2. Cooperative candidate reports (from cooperating vehicles within R_sense = 40m)
        for vru in seq.vrus:
            if not (vru.start_frame <= k < vru.end_frame):
                continue
            idx = k - vru.start_frame
            vru_pos = vru.trajectory[idx, :2]

            # Check if any sender has VRU within sensing radius R_sense = 40m
            for sender in seq.senders:
                sender_pos = sender.trajectory[k, :2]
                s_dist = float(np.linalg.norm(vru_pos - sender_pos))
                if s_dist <= R_SENSE:
                    # Within sender FOV -> eligible cooperative opportunity
                    cooperative_reports[k].append((vru_pos, vru.track_id, s_dist))
                    break  # One primary report per VRU

    return passive_detections, cooperative_reports
